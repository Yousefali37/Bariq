export const journalTags = [
  'All',
  ...Array.from(new Set(journal.flatMap((article) => article.tags))).sort(),
]

export function getArticle(slug) {
  return journal.find((article) => article.slug === slug)
}

export function getNextArticle(slug) {
  const index = journal.findIndex((article) => article.slug === slug)
  return journal[(index + 1) % journal.length]
}

export function getRelatedArticles(article, limit = 2) {
  if (!article) return journal.slice(0, limit)
  const explicit = (article.related || [])
    .map((slug) => getArticle(slug))
    .filter(Boolean)
  if (explicit.length >= limit) return explicit.slice(0, limit)
  const fallback = journal.filter(
    (item) =>
      item.slug !== article.slug &&
      !explicit.some((entry) => entry.slug === item.slug),
  )
  return [...explicit, ...fallback].slice(0, limit)
}

export function filterArticlesByTag(tag) {
  if (!tag || tag === 'All') return journal
  return journal.filter((article) => article.tags.includes(tag))
}
